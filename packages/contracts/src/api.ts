import { z } from 'zod';
import { RunAction } from './legality.js';
import {
  AgentStatus,
  AssessmentStatus,
  DomainSource,
  LostReason,
  RiskLevel,
  TECHNIQUES,
} from './vocabulary.js';

// The HTTP API's request and response shapes (plan §6, D13). The API builds its responses from these types,
// and the web app parses every response with these schemas: one definition, so the two can't drift.

/** Per-run limits and defaults. The database's CHECK constraints say the same; this is where to change them. */
export const RUN_LIMITS = {
  domainMaxLength: 253,
  agentCount: { min: 1, max: 20, default: 6 },
  windowSize: { min: 1, default: 2 },
  stallTimeoutS: { min: 10, max: 600, default: 60 },
  maxAgentDurationS: { min: 30, max: 3600, default: 300 },
  failFirstAttempts: { min: 0, max: 5, default: 0 },
} as const;

const int = (limits: { min: number; max?: number }) =>
  limits.max === undefined ? z.int().min(limits.min) : z.int().min(limits.min).max(limits.max);

export const SubmitRequestSchema = z
  .object({
    /** Generated by the browser and kept for retries, so a repeated submit is harmless (D12). */
    id: z.uuid(),
    /** Never checked for support here: agent-service's 422 path must stay reachable (R5). */
    domain: z.string().trim().toLowerCase().min(1).max(RUN_LIMITS.domainMaxLength),
    agentCount: int(RUN_LIMITS.agentCount),
    windowSize: int(RUN_LIMITS.windowSize),
    stallTimeoutS: int(RUN_LIMITS.stallTimeoutS).default(RUN_LIMITS.stallTimeoutS.default),
    maxAgentDurationS: int(RUN_LIMITS.maxAgentDurationS).default(RUN_LIMITS.maxAgentDurationS.default),
    failFirstAttempts: int(RUN_LIMITS.failFirstAttempts).default(RUN_LIMITS.failFirstAttempts.default),
  })
  .refine((request) => request.windowSize <= request.agentCount, {
    path: ['windowSize'],
    message: 'window must not exceed the number of agents',
  });
/** What the browser sends (the optional settings may be left out). */
export type SubmitRequest = z.input<typeof SubmitRequestSchema>;
/** What the API works with after validation (defaults filled in). */
export type ValidSubmitRequest = z.output<typeof SubmitRequestSchema>;

export const SubmitResponseSchema = z.object({ id: z.uuid() });
export type SubmitResponse = z.infer<typeof SubmitResponseSchema>;

export const WindowRequestSchema = z.object({ size: z.int().min(RUN_LIMITS.windowSize.min) });
export type WindowRequest = z.infer<typeof WindowRequestSchema>;

export const WindowResponseSchema = z.object({ window: z.int() });
export type WindowResponse = z.infer<typeof WindowResponseSchema>;

export const ActionResponseSchema = z.object({ status: z.enum(AssessmentStatus) });
export type ActionResponse = z.infer<typeof ActionResponseSchema>;

/** A request the workflow hasn't acted on yet; while one is pending, no other action is allowed. */
export const PendingRequest = {
  Cancelling: 'cancelling',
  Approving: 'approving',
  Rejecting: 'rejecting',
} as const;
export type PendingRequest = (typeof PendingRequest)[keyof typeof PendingRequest];

const SummarySchema = z.object({
  uniqueDomains: z.int(),
  critical: z.int(),
  high: z.int(),
  medium: z.int(),
  low: z.int(),
});

const AgentViewSchema = z.object({
  index: z.int(),
  technique: z.enum(TECHNIQUES),
  status: z.enum(AgentStatus),
  progress: z.number().min(0).max(1),
  discoveredCount: z.int().nullable(),
  lostReason: z.enum(LostReason).nullable(),
  /** false = "stop unconfirmed" (D6); null = never stopped. */
  stopConfirmed: z.boolean().nullable(),
  /** Pod name of the worker handling it. */
  worker: z.string().nullable(),
});
export type AgentView = z.infer<typeof AgentViewSchema>;

/** How many of the run's agents are in each state. */
const RunCountsSchema = z.object({
  queued: z.int(),
  /** Starting or running. */
  running: z.int(),
  completed: z.int(),
  failed: z.int(),
  lost: z.int(),
  stopped: z.int(),
});
export type RunCounts = z.infer<typeof RunCountsSchema>;

export const RunViewSchema = z.object({
  id: z.uuid(),
  domain: z.string(),
  agentCount: z.int(),
  window: z.int(),
  status: z.enum(AssessmentStatus),
  pending: z.enum(PendingRequest).nullable(),
  counts: RunCountsSchema,
  summary: SummarySchema.nullable(),
  agents: z.array(AgentViewSchema),
  /** What the UI may offer now: the legality table, empty while a request is pending. */
  allowedActions: z.array(z.enum(RunAction)),
  failureReason: z.string().nullable(),
  createdAt: z.iso.datetime(),
  updatedAt: z.iso.datetime(),
});
export type RunView = z.infer<typeof RunViewSchema>;

export const RunListSchema = z.array(
  z.object({
    id: z.uuid(),
    domain: z.string(),
    status: z.enum(AssessmentStatus),
    agentCount: z.int(),
    createdAt: z.iso.datetime(),
  }),
);
export type RunList = z.infer<typeof RunListSchema>;

export const DomainsResponseSchema = z.discriminatedUnion('source', [
  z.object({
    source: z.literal(DomainSource.Staged),
    domains: z.array(z.object({ domain: z.string(), risk: z.enum(RiskLevel), foundBy: z.int() })),
  }),
  z.object({
    source: z.literal(DomainSource.Final),
    domains: z.array(z.object({ domain: z.string(), risk: z.enum(RiskLevel) })),
  }),
]);
export type DomainsResponse = z.infer<typeof DomainsResponseSchema>;

export const ErrorCode = {
  ValidationFailed: 'validation_failed',
  NotFound: 'not_found',
  IdConflict: 'id_conflict',
  NotAllowed: 'not_allowed',
  Unavailable: 'unavailable',
} as const;
export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode];

export const ErrorResponseSchema = z.object({ error: z.enum(ErrorCode), message: z.string() });
export type ErrorResponse = z.infer<typeof ErrorResponseSchema>;
